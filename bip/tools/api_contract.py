"""Generate ``docs/API_REFERENCE.md`` from the application's OpenAPI document.

``python -m bip.tools.api_contract`` writes the file; ``--check`` exits non-zero when the committed
file differs from what the code would generate, so the reference cannot drift from the API. The
required role of every route comes from :func:`bip.api.access.required_role`, the same function the
protection middleware enforces.
"""

from __future__ import annotations

import argparse
import sys
import tempfile
from collections import defaultdict
from pathlib import Path
from typing import Any

from bip.api.access import required_role
from bip.api.app import API_PREFIX, create_app
from bip.config.settings import load_settings

TARGET = Path(__file__).resolve().parents[2] / "docs" / "API_REFERENCE.md"

INTRO = """\
# BIP API reference

_Generated by `python -m bip.tools.api_contract` from the application's OpenAPI document. Do not
edit by hand; `tests/unit/test_api_reference.py` fails when this file is out of date._

The live, machine-readable contract is served at `{prefix}/openapi.json` (interactive docs at
`{prefix}/docs`). This file adds the conventions that the schema cannot express.

## Conventions

* **Base path and version.** Every route lives under `{prefix}`. A breaking change gets a new
  prefix; additive changes do not.
* **Errors.** Every error has the shape
  `{{"error": {{"code": "...", "message": "...", "details": ...}}}}`. Codes by status:
  400/422 `validation_error` (malformed request, with `details`) and `invalid_input` (a valid
  request the data refuses); 401 `unauthenticated` and `invalid_credentials`; 403 `forbidden`,
  `csrf_failed` and `origin_denied`; 404 `not_found`; 409 `conflict`, `ingestion_busy`,
  `discovery_busy`, `job_busy`, `auth_disabled`, `workers_disabled` and `backup_failed`;
  429 `rate_limited` (with `Retry-After`); 502 `upstream_failed` and `upstream_invalid`;
  503 `database_unavailable`, `no_eligible_provider` and `ml_unavailable`; 507 `storage_limit`;
  500 `internal_error`.
* **Pagination.** List endpoints take `limit` and `offset` and return
  `{{"total", "limit", "offset", "items"}}`. Limits are bounded (see each route).
* **Data origin.** Intelligence and discovery responses carry `data_origin`. It is
  `stored_observations` for real stored data and `offline_fixture` when the data comes from BIP's
  deterministic fixtures. Fixture data is never presented as real.
* **Finality.** Chain records carry `finality`: `observed` (seen, may still reorganise),
  `confirmed`, `finalized`, or `orphaned` (reorganised away). Orphaned data is excluded from every
  derived figure and from every signal, relationship and score; it is only listed, labelled.
* **Evidence classes.** Observed facts, calculated metrics, hypotheses and verified attribution are
  kept apart. A `hypothesis` or a signal is a candidate to review, never a finding.
* **Coverage.** Responses say what they cover and what they cannot see (`coverage`, `scope`,
  `not_known`, `limitations`). Missing data is `null`, never zero.

## Authentication

`GET {prefix}/auth/status` is public and tells a client which mode the server runs in.

* `mode = disabled`: local single-user mode, no sign-in. The server only starts this way on a
  loopback address.
* `mode = required`: sign in with `POST {prefix}/auth/login` (`username`, `password`). The server
  sets an `HttpOnly`, `SameSite=Strict` cookie `bip_session` and returns a `csrf_token`. Send that
  token in an `X-CSRF-Token` header on every `POST`, `PATCH` and `DELETE`, and keep requests
  `same-origin` or from an origin allowed by the server. `POST {prefix}/auth/logout` ends the
  session. Sessions expire after a fixed time and when idle. Five failed sign-ins lock the account
  for a while; the sign-in endpoint and the API as a whole are rate limited per client address.
* Roles: `viewer` (all reads), `analyst` (changes to analysis data: watchlists, cases, signals,
  alerts, labels, discovery, relationships, research), `admin` (everything that contacts a
  provider, changes provider state, trains a model, manages users or reads the audit log). A route
  not listed as analyst-level is admin-only. The **Role** column below is the role each route needs.

## Routes
"""


def _schema(spec: dict[str, Any], node: dict[str, Any] | None) -> str:
    if not node:
        return ""
    if "$ref" in node:
        return str(node["$ref"]).rsplit("/", 1)[-1]
    if "anyOf" in node:
        return " or ".join(sorted({_schema(spec, n) or "null" for n in node["anyOf"]}))
    kind = node.get("type", "")
    if kind == "array":
        return f"list of {_schema(spec, node.get('items')) or 'any'}"
    if "enum" in node:
        return " | ".join(f"`{v}`" for v in node["enum"])
    extras: list[str] = []
    for key, label in (
        ("minimum", ">="),
        ("maximum", "<="),
        ("minLength", "len>="),
        ("maxLength", "len<="),
    ):
        if key in node:
            extras.append(f"{label}{node[key]}")
    return str(kind) + (f" ({', '.join(extras)})" if extras else "")


def _body_fields(spec: dict[str, Any], op: dict[str, Any]) -> list[str]:
    content = op.get("requestBody", {}).get("content", {}).get("application/json", {})
    ref = content.get("schema", {}).get("$ref")
    if not ref:
        return []
    model = spec["components"]["schemas"][ref.rsplit("/", 1)[-1]]
    required = set(model.get("required", []))
    return [
        f"`{name}`{' *' if name in required else ''}: {_schema(spec, prop) or 'any'}"
        for name, prop in model.get("properties", {}).items()
    ]


def build_reference() -> str:
    with tempfile.TemporaryDirectory() as tmp:
        app = create_app(load_settings(data_root=Path(tmp) / "data", env="test"))
        spec = app.openapi()
    groups: dict[str, list[tuple[str, str, dict[str, Any]]]] = defaultdict(list)
    for path, ops in spec["paths"].items():
        for method, op in ops.items():
            tag = (op.get("tags") or ["other"])[0]
            groups[tag].append((path, method.upper(), op))
    lines = [INTRO.format(prefix=API_PREFIX)]
    total = sum(len(v) for v in groups.values())
    lines.append(f"{total} routes in {len(groups)} groups.\n")
    for tag in sorted(groups):
        lines.append(f"### {tag}\n")
        lines.append("| Method | Path | Role | Summary |")
        lines.append("|---|---|---|---|")
        for path, method, op in sorted(groups[tag], key=lambda x: (x[0], x[1])):
            rel = path[len(API_PREFIX) :]
            role = required_role(method, rel) or "public"
            summary = (op.get("summary") or "").replace("|", "/")
            detail = (op.get("description") or "").strip().splitlines()
            if detail and detail[0].strip():
                summary = f"{summary}: {detail[0].strip()}".replace("|", "/")
            lines.append(f"| {method} | `{path}` | {role} | {summary} |")
        lines.append("")
        for path, method, op in sorted(groups[tag], key=lambda x: (x[0], x[1])):
            params = [
                f"`{p['name']}` ({p['in']}{', required' if p.get('required') else ''}): "
                f"{_schema(spec, p.get('schema'))}"
                for p in op.get("parameters", [])
            ]
            body = _body_fields(spec, op)
            if not params and not body:
                continue
            lines.append(f"<details><summary><code>{method} {path}</code></summary>\n")
            if params:
                lines.append("Parameters: " + "; ".join(params) + "\n")
            if body:
                lines.append("Body (`*` required): " + "; ".join(body) + "\n")
            lines.append("</details>\n")
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the file is out of date")
    args = parser.parse_args(argv)
    text = build_reference()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != text:
            sys.stderr.write(
                "docs/API_REFERENCE.md is out of date: run python -m bip.tools.api_contract\n"
            )
            return 1
        return 0
    TARGET.write_text(text, encoding="utf-8")
    sys.stdout.write(f"wrote {TARGET}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
