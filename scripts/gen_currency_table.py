"""Generate the frontend currency-exponent module from watchtower/currency_exponents.json (the single source).

    python scripts/gen_currency_table.py          # writes frontend/src/lib/currencyExponents.generated.ts
    python scripts/gen_currency_table.py --check  # exit 1 if the committed file is out of date

tests/test_currency.py runs the same check, so a stale generated file fails the test suite.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "watchtower" / "currency_exponents.json"
TARGET = ROOT / "frontend" / "src" / "lib" / "currencyExponents.generated.ts"


def render() -> str:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    zero = ", ".join(f"'{c}'" for c in sorted(data["zero_decimal"]))
    three = ", ".join(f"'{c}'" for c in sorted(data["three_decimal"]))
    return (
        "// GENERATED by scripts/gen_currency_table.py from watchtower/currency_exponents.json. Do not edit by hand.\n"
        f"export const ZERO_DECIMAL: ReadonlySet<string> = new Set([{zero}]);\n"
        f"export const THREE_DECIMAL: ReadonlySet<string> = new Set([{three}]);\n"
    )


def main(argv) -> int:
    text = render()
    if "--check" in argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            print("currencyExponents.generated.ts is out of date: run python scripts/gen_currency_table.py", file=sys.stderr)
            return 1
        print("up to date")
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
